-- Vue 1 : Détails d'un événement avec sa salle
CREATE OR REPLACE VIEW v_evenement_details AS
SELECT
    e.id,
    e.titre,
    e.description,
    e.horaire,
    e.placement_libre,
    s.id AS salle_id,
    s.nom AS salle_nom,
    s.ville AS salle_ville,
    s.capacite AS salle_capacite,
    s.adresse AS salle_adresse
FROM evenement e
JOIN salle s ON e.salle_id = s.id;

-- Vue 2 : Statistiques agrégées par client
CREATE OR REPLACE VIEW v_client_stats AS
SELECT
    c.id AS client_id,
    COUNT(r.id) AS nb_reservations,
    COUNT(r.id) FILTER (WHERE r.statut_id = 2) AS nb_validees,
    COUNT(r.id) FILTER (WHERE r.statut_id = 3) AS nb_annulees,
    COUNT(r.id) FILTER (WHERE r.statut_id = 4) AS nb_remboursees,
    COALESCE(SUM(r.montant_total), 0::NUMERIC) AS ca_brut,
    COALESCE(SUM(r.montant_total) FILTER (WHERE r.statut_id <> 3), 0::NUMERIC) AS ca_hors_annulees,
    COALESCE(SUM(r.montant_rembourse), 0::NUMERIC) AS total_rembourse,
    COALESCE(SUM(r.montant_total), 0::NUMERIC) - COALESCE(SUM(r.montant_rembourse), 0::NUMERIC) AS net,
    COUNT(DISTINCT r.evenement_id) AS nb_evenements,
    MIN(r.date_creation) AS premiere_reservation,
    MAX(r.date_creation) AS derniere_reservation
FROM client c
LEFT JOIN reservation r ON r.client_id = c.id
GROUP BY c.id;

-- Vue 3 : Places libres par événement et catégorie (F17)
CREATE OR REPLACE VIEW vue_places_libres AS
SELECT
    (e.id || '-' || c.libelle) AS id,
    e.id AS evenement_id,
    c.libelle AS categorie,
    COUNT(p.id) AS places_disponibles
FROM evenement e
JOIN salle s ON e.salle_id = s.id
JOIN place p ON p.salle_id = s.id
JOIN categorie c ON p.categorie_id = c.id
WHERE NOT EXISTS (
    SELECT 1
    FROM billet b
    JOIN reservation r ON b.reservation_id = r.id
    JOIN statut st ON r.statut_id = st.id
    WHERE b.place_id = p.id
      AND r.evenement_id = e.id
      AND st.libelle IN ('PROVISOIRE', 'PAYEE')
)
GROUP BY e.id, c.libelle;

-- Vue 4 : Taux de remplissage par événement et catégorie (F18)
CREATE OR REPLACE VIEW v_evenement_remplissage_categorie AS
SELECT
    CONCAT(e.id, '_', c.id) AS id,
    e.id AS evenement_id,
    c.libelle AS nom_categorie,
    COUNT(DISTINCT p.id) AS total_places,
    COUNT(DISTINCT CASE WHEN UPPER(s.libelle) = 'PROVISOIRE' THEN COALESCE(b.id, r.id) END) AS places_provisoires,
    COUNT(DISTINCT CASE WHEN UPPER(s.libelle) = 'PAYEE' THEN COALESCE(b.id, r.id) END) AS places_payees
FROM evenement e
JOIN salle sal ON e.salle_id = sal.id
JOIN place p ON p.salle_id = sal.id
JOIN categorie c ON p.categorie_id = c.id
LEFT JOIN billet b ON b.place_id = p.id
LEFT JOIN reservation r ON (r.id = b.reservation_id OR r.place_id = p.id) AND r.evenement_id = e.id
LEFT JOIN statut s ON r.statut_id = s.id
GROUP BY e.id, c.id, c.libelle;
