CREATE TABLE IF NOT EXISTS statut (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(255) NOT NULL,
    CONSTRAINT uk_statut_libelle UNIQUE (libelle)
);

CREATE TABLE IF NOT EXISTS categorie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(30) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uk_categorie_libelle UNIQUE (libelle)
);

CREATE TABLE IF NOT EXISTS salle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    ville VARCHAR(50) NOT NULL,
    adresse VARCHAR(255) NOT NULL,
    capacite INTEGER NOT NULL,
    CONSTRAINT uk_salle_nom_ville UNIQUE (nom, ville)
);

CREATE TABLE IF NOT EXISTS evenement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre VARCHAR(150) NOT NULL,
    description VARCHAR(255),
    horaire TIMESTAMP(6) WITHOUT TIME ZONE,
    placement_libre BOOLEAN,
    salle_id BIGINT,
    CONSTRAINT uk_evenement_titre_horaire UNIQUE (titre, horaire),
    CONSTRAINT fk_evenement_salle FOREIGN KEY (salle_id) REFERENCES salle(id)
);

CREATE TABLE IF NOT EXISTS place (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rang INTEGER NOT NULL,
    numero INTEGER NOT NULL,
    salle_id BIGINT NOT NULL,
    categorie_id BIGINT NOT NULL,
    CONSTRAINT uk_place_salle_rang_numero UNIQUE (salle_id, rang, numero),
    CONSTRAINT fk_place_salle FOREIGN KEY (salle_id) REFERENCES salle(id),
    CONSTRAINT fk_place_categorie FOREIGN KEY (categorie_id) REFERENCES categorie(id)
);

CREATE TABLE IF NOT EXISTS client (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(50) NOT NULL,
    prenom VARCHAR(50) NOT NULL,
    telephone VARCHAR(20),
    email VARCHAR(100),
    CONSTRAINT uk_client_nom_prenom UNIQUE (nom, prenom),
    CONSTRAINT uk_client_telephone UNIQUE (telephone),
    CONSTRAINT uk_client_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS tarif_evenement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prix NUMERIC(38, 2) NOT NULL,
    evenement_id BIGINT,
    CONSTRAINT fk_tarif_evenement FOREIGN KEY (evenement_id) REFERENCES evenement(id)
);

CREATE TABLE IF NOT EXISTS reservation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_creation TIMESTAMP(6) WITHOUT TIME ZONE,
    date_paiement TIMESTAMP(6) WITHOUT TIME ZONE,
    date_annulation TIMESTAMP(6) WITHOUT TIME ZONE,
    montant_total NUMERIC(38, 2) NOT NULL,
    montant_rembourse NUMERIC(38, 2),
    est_rembourse BOOLEAN,
    place_id BIGINT,
    client_id BIGINT,
    evenement_id BIGINT,
    statut_id BIGINT,
    CONSTRAINT fk_reservation_client FOREIGN KEY (client_id) REFERENCES client(id),
    CONSTRAINT fk_reservation_evenement FOREIGN KEY (evenement_id) REFERENCES evenement(id),
    CONSTRAINT fk_reservation_statut FOREIGN KEY (statut_id) REFERENCES statut(id)
);

CREATE TABLE IF NOT EXISTS paiement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    montant NUMERIC(38, 2) NOT NULL,
    date_paiement TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    mode_paiement VARCHAR(50),
    reservation_id BIGINT NOT NULL,
    CONSTRAINT fk_paiement_reservation FOREIGN KEY (reservation_id) REFERENCES reservation(id)
);

CREATE TABLE IF NOT EXISTS remboursement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    montant NUMERIC(10, 2) NOT NULL,
    date_remboursement TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    mode_remboursement VARCHAR(255),
    motif VARCHAR(255),
    reservation_id BIGINT NOT NULL,
    CONSTRAINT fk_remboursement_reservation FOREIGN KEY (reservation_id) REFERENCES reservation(id)
);

CREATE TABLE IF NOT EXISTS billet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    place_id BIGINT NOT NULL,
    prix_applique NUMERIC(10, 2) NOT NULL,
    code_billet VARCHAR(100),
    CONSTRAINT uk_billet_reservation_place UNIQUE (reservation_id, place_id),
    CONSTRAINT uk_billet_code UNIQUE (code_billet),
    CONSTRAINT fk_billet_reservation FOREIGN KEY (reservation_id) REFERENCES reservation(id),
    CONSTRAINT fk_billet_place FOREIGN KEY (place_id) REFERENCES place(id)
);

